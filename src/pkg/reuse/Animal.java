package pkg.reuse;

public class Animal {
    private String name;
    private boolean canEat;

    public void setName(String name) {
        this.name = name;
    }

    public void setCanEat(boolean canEat) {
        this.canEat = canEat;
    }

    public String getName() {
        return name;
    }

    public boolean isCanEat() {
        return canEat;
    }
}
